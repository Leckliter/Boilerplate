'use client';

/**
 * Every icon the app uses (Phosphor). Import icons from here, never from
 * `@phosphor-icons/react` directly: this file is the one place the icon weight
 * is set (see `IconProvider`), and it works in server and client components.
 * Need a new icon? Add it to the export list below.
 */
import { IconContext } from '@phosphor-icons/react';
import type { ReactNode } from 'react';

export type { Icon, IconProps, IconWeight } from '@phosphor-icons/react';

const ICON_CONTEXT = { weight: 'light' as const };

/** Mounted once in the root layout: makes every icon the light weight. Pass `weight="fill"` for an active/selected state. */
export function IconProvider({ children }: { children: ReactNode }) {
  return <IconContext.Provider value={ICON_CONTEXT}>{children}</IconContext.Provider>;
}

