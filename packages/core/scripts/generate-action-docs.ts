/**
 * Writes docs/actions.generated.md — the full catalog of actions with their
 * permissions and input schemas. Generated from the code so it can never drift.
 * (The events module adds docs/events.generated.md from its own catalog.)
 *
 *   pnpm actions:docs           # regenerate
 *   pnpm actions:docs --check   # CI: fail if the file is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { z } from 'zod';

import { PERMISSIONS, ROLE_PERMISSIONS } from '../src/access';
import { listActions } from '../src/actions/registry';

const out = fileURLToPath(new URL('../../../docs/actions.generated.md', import.meta.url));

const lines: string[] = [
  '<!-- GENERATED by `pnpm actions:docs` from packages/core/src/actions. Do not edit by hand. -->',
  '',
  '# Action catalog',
  '',
  'Every action can be called from server code (`callAction`), over REST',
  '(`POST /api/v1/actions/<name>`) and over MCP (tool name = action name with `.` → `_`).',
  'See [actions.md](./actions.md) for how the system works.',
  '',
  '## Permissions by role',
  '',
  `| Permission | Meaning | ${Object.keys(ROLE_PERMISSIONS).join(' | ')} |`,
  `| --- | --- | ${Object.keys(ROLE_PERMISSIONS)
    .map(() => ':-:')
    .join(' | ')} |`,
  ...Object.entries(PERMISSIONS).map(
    ([p, d]) =>
      `| \`${p}\` | ${d} | ${Object.values(ROLE_PERMISSIONS)
        .map((perms) => ((perms as readonly string[]).includes(p) ? '✓' : ''))
        .join(' | ')} |`,
  ),
  '',
  '## Actions',
  '',
  '| Action | Who can run it | Changes data |',
  '| --- | --- | :-: |',
  ...listActions().map(
    (a) =>
      `| [\`${a.name}\`](#${a.name.replace('.', '')}) | \`${a.audience}\` | ${a.mutates ? 'yes' : ''} |`,
  ),
  '',
];

for (const a of listActions()) {
  lines.push(
    `### ${a.name}`,
    '',
    `**${a.title}** — ${a.description}`,
    '',
    `- Who: \`${a.audience}\``,
    `- Changes data: ${a.mutates ? 'yes (written to the activity log)' : 'no'}`,
    ...(a.rateLimit
      ? [`- Rate limit: ${a.rateLimit.limit} per ${a.rateLimit.perSeconds}s per caller`]
      : []),
    ...(a.humanCheck
      ? ['- Guests must pass the human check (Turnstile) when it is configured']
      : []),
    `- Returns: ${a.returns}`,
    '',
    '```json',
    JSON.stringify(z.toJSONSchema(a.input, { io: 'input', unrepresentable: 'any' }), null, 2),
    '```',
    '',
  );
}

const files: [string, string, string][] = [
  [out, lines.join('\n'), `${listActions().length} actions`],
];
if (process.argv.includes('--check')) {
  let stale = false;
  for (const [file, content] of files) {
    const current = (() => {
      try {
        return readFileSync(file, 'utf8');
      } catch {
        // Expected: the docs haven't been generated yet.
        return '';
      }
    })();
    if (current !== content) {
      console.error(
        `${file.split('/').slice(-2).join('/')} is out of date. Run \`pnpm actions:docs\`.`,
      );
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('Action docs are up to date.');
} else {
  for (const [file, content, what] of files) {
    writeFileSync(file, content);
    console.log(`Wrote ${file} (${what}).`);
  }
}
